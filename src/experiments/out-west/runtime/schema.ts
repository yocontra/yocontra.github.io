import { type SchemaType, schema, t } from '@colyseus/schema'
/** Public replicated fields; nested movement keeps each schema below 63 fields. */
export const MotionRecord = schema(
  {
    vaultArc: t.float32(),
    roof: t.number(),
    climbTicks: t.number(),
    climbDeck: t.number(),
    climbDir: t.number(),
    fallTicks: t.number(),
    fallTotal: t.number(),
    fallFromX: t.number(),
    fallFromZ: t.number(),
    fallFromY: t.number(),
    fallToX: t.number(),
    fallToY: t.number(),
    fallToZ: t.number(),
    rollTicks: t.number(),
    rollCooldown: t.number(),
    rollDirX: t.number(),
    rollDirZ: t.number(),
    jumpTicks: t.number(),
    jumpCooldown: t.number(),
    vaultStep: t.number(),
    vaultAim: t.number(),
    sprinting: t.boolean(),
    sprintLock: t.number(),
    sprintOut: t.number(),
    slideTicks: t.number(),
    slideCooldown: t.number(),
    slideAim: t.number(),
    airX: t.number(),
    airZ: t.number(),
    support: t.number(),
    airPeakY: t.number(),
    mantleTicks: t.number(),
    mantleFromX: t.number(),
    mantleFromY: t.number(),
    mantleFromZ: t.number(),
    mantleToX: t.number(),
    mantleToY: t.number(),
    mantleToZ: t.number(),
    fallDamage: t.number(),
  },
  'MotionRecord',
)
export type MotionRecord = SchemaType<typeof MotionRecord>
/** Public replicated fields; nested movement keeps each schema below 63 fields. */
