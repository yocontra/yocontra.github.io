import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import type { ContentAsset } from '../../src/experiments/out-west/content/types.ts'
import { CATALOG } from '../../src/experiments/out-west/data/catalog.ts'

export async function buildManifest(): Promise<void> {
  const assets: Record<string, ContentAsset> = {}
  const names = [
    'frontier',
    'duel',
    'depot',
    'mission',
    'bank',
    'player',
    'moves',
    ...Array.from({ length: 17 }, (_, i) => `outlaw-${i}`),
  ]
  for (const name of names) {
    const url = `/experiments/out-west/3d/baked/${name}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    assets[name] = { url: `${url}?v=${hash.slice(0, 16)}`, hash, bytes: bytes.byteLength }
  }
  const dynamic: Record<string, ContentAsset> = {}
  for (const name of [
    'rifle',
    'shotgun',
    'dynamite',
    'strongbox',
    'bag0',
    'bag1',
    'bag2',
    'bag3',
    'coin',
    'card',
    'crow',
    'tumbleweed',
    'door',
    'dog',
    'horse',
  ]) {
    const url = `/experiments/out-west/3d/dynamic/${name}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    dynamic[name] = { url: `${url}?v=${hash.slice(0, 16)}`, hash, bytes: bytes.byteLength }
  }
  const equipment: Record<string, ContentAsset> = {}
  for (const item of CATALOG.filter((candidate) =>
    ['outfit', 'hat', 'gun', 'spurs', 'extra', 'holster'].includes(candidate.slot),
  )) {
    const url = `/experiments/out-west/3d/equipment/${item.id}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    equipment[item.id] = { url: `${url}?v=${hash.slice(0, 16)}`, hash, bytes: bytes.byteLength }
  }
  await writeFile(
    'src/experiments/out-west/content/equipment.ts',
    `// Generated by tools/content/manifest.ts.\nexport const EQUIPMENT = ${JSON.stringify(equipment, null, 2)} as const\n`,
  )
  const environmentPath = '/experiments/out-west/3d/env/kloppenheim_06_puresky_1k.hdr'
  const environmentBytes = await readFile(`public${environmentPath}`)
  const environmentHash = createHash('sha256').update(environmentBytes).digest('hex')
  const environment = {
    url: `${environmentPath}?v=${environmentHash.slice(0, 16)}`,
    hash: environmentHash,
    bytes: environmentBytes.byteLength,
  }
  const collision = JSON.parse(
    await readFile('src/experiments/out-west/content/collision.json', 'utf8'),
  ) as { version: string }
  const arenaConfigs = await Promise.all(
    ['depot', 'mission', 'bank'].map((name) =>
      readFile(`src/experiments/out-west/content/${name}.json`, 'utf8'),
    ),
  )
  const version = createHash('sha256')
    .update(JSON.stringify(assets))
    .update(JSON.stringify(dynamic))
    .update(JSON.stringify(arenaConfigs))
    .update(JSON.stringify(equipment))
    .update(JSON.stringify(environment))
    .update(collision.version)
    .digest('hex')
  await writeFile(
    'src/experiments/out-west/content/manifest.ts',
    `// Generated by tools/content/manifest.ts. URLs are immutable for a content revision.\nexport const DYNAMIC_ASSETS = ${JSON.stringify(dynamic)} as const\nexport const ENVIRONMENT = ${JSON.stringify(environment)} as const\nexport const CONTENT_VERSION = '${version}'\nexport const COLLISION_VERSION = '${collision.version}'\nexport const ASSETS = ${JSON.stringify(assets, null, 2)} as const\nexport const TOWN_BOUNDS = { minX: 0, minZ: 0, maxX: 144, maxZ: 144 } as const\nexport const FRONTIER_SPAWN = [72, 0, 66] as const\n`,
  )
}
if (import.meta.main) {
  await buildManifest()
}
