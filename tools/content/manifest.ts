import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { AMBIENT_ASSETS } from '../../src/experiments/out-west/content/ambient.ts'
import lighting from '../../src/experiments/out-west/content/lighting.json' with { type: 'json' }
import { FRONTIER_SPAWN as previousArrival } from '../../src/experiments/out-west/content/manifest.ts'
import { SKIES } from '../../src/experiments/out-west/content/skies.ts'
import streetLife from '../../src/experiments/out-west/content/street-life.json' with {
  type: 'json',
}
import type { ContentAsset } from '../../src/experiments/out-west/content/types.ts'
import { CATALOG } from '../../src/experiments/out-west/data/catalog.ts'
import { TOWN } from '../../src/experiments/out-west/ffa/sim/layout.ts'
import { formatContent } from './format-content.ts'

export async function buildManifest(): Promise<void> {
  const published = JSON.parse(await readFile('tools/art/environments/frontier.json', 'utf8')) as {
    arrival?: readonly number[]
  }
  const arrival = published.arrival ?? previousArrival
  const assets: Record<string, ContentAsset> = {}
  const names = [
    'frontier',
    'duel',
    'depot',
    'mission',
    'bank',
    'player',
    'moves',
    ...Array.from({ length: 17 }, (_, i) => `outlaw-${i}`),
  ]
  for (const name of names) {
    const url = `/experiments/out-west/3d/native-v2/baked/${name}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    assets[name] = { url: `${url}?v=${hash.slice(0, 16)}`, hash, bytes: bytes.byteLength }
  }
  const dynamic: Record<string, ContentAsset> = {}
  for (const name of [
    'rifle',
    'shotgun',
    'dynamite',
    'strongbox',
    'bag0',
    'bag1',
    'bag2',
    'bag3',
    'coin',
    'card',
    'crow',
    'tumbleweed',
    'door',
    'dog',
    'horse',
    'held-rifle',
    'held-shotgun',
  ]) {
    const prefix = [
      'bag0',
      'bag1',
      'bag2',
      'bag3',
      'strongbox',
      'dynamite',
      'coin',
      'tumbleweed',
      'crow',
      'dog',
      'horse',
      'held-rifle',
      'held-shotgun',
    ].includes(name)
      ? 'native-v2/'
      : ''
    const url = `/experiments/out-west/3d/${prefix}dynamic/${name}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    dynamic[name] = { url: `${url}?v=${hash.slice(0, 16)}`, hash, bytes: bytes.byteLength }
  }
  const equipment: Record<string, ContentAsset & { pair?: ContentAsset }> = {}
  for (const item of CATALOG.filter((candidate) =>
    ['outfit', 'hat', 'gun', 'spurs', 'extra', 'holster'].includes(candidate.slot),
  )) {
    const url = `/experiments/out-west/3d/native-v2/equipment/${item.id}.glb`
    const bytes = await readFile(`public${url}`)
    const hash = createHash('sha256').update(bytes).digest('hex')
    const entry: ContentAsset & { pair?: ContentAsset } = {
      url: `${url}?v=${hash.slice(0, 16)}`,
      hash,
      bytes: bytes.byteLength,
    }
    equipment[item.id] = entry
    if (item.slot === 'outfit' || item.slot === 'holster') {
      const pairUrl = `/experiments/out-west/3d/native-v2/equipment/${item.id}.pair.glb`
      const pairBytes = await readFile(`public${pairUrl}`)
      const pairHash = createHash('sha256').update(pairBytes).digest('hex')
      entry.pair = {
        url: `${pairUrl}?v=${pairHash.slice(0, 16)}`,
        hash: pairHash,
        bytes: pairBytes.byteLength,
      }
    }
  }
  await writeFile(
    'src/experiments/out-west/content/equipment.ts',
    `// Generated by tools/content/manifest.ts.\nexport const EQUIPMENT = ${JSON.stringify(equipment, null, 2)} as const\n`,
  )
  const environmentPath = '/experiments/out-west/3d/env/kloppenheim_06_puresky_1k.hdr'
  const environmentBytes = await readFile(`public${environmentPath}`)
  const environmentHash = createHash('sha256').update(environmentBytes).digest('hex')
  const environment = {
    url: `${environmentPath}?v=${environmentHash.slice(0, 16)}`,
    hash: environmentHash,
    bytes: environmentBytes.byteLength,
  }
  const collision = JSON.parse(
    await readFile('src/experiments/out-west/content/collision.json', 'utf8'),
  ) as { version: string }
  const arenaConfigs = await Promise.all(
    ['depot', 'mission', 'bank'].map((name) =>
      readFile(`src/experiments/out-west/content/${name}.json`, 'utf8'),
    ),
  )
  const ambient = Object.fromEntries(
    await Promise.all(
      Object.entries(AMBIENT_ASSETS).map(async ([name, previous]) => {
        const url = previous.url.split('?')[0] ?? previous.url
        const bytes = await readFile(`public${url}`)
        const hash = createHash('sha256').update(bytes).digest('hex')
        return [name, { url: `${url}?v=${hash.slice(0, 16)}`, bytes: bytes.byteLength, hash }]
      }),
    ),
  )
  await writeFile(
    'src/experiments/out-west/content/ambient.ts',
    `// Authored native ambient assets, versioned by tools/content/manifest.ts.\nexport const AMBIENT_ASSETS = ${JSON.stringify(ambient, null, 2)} as const\n`,
  )
  const atmosphere = [ambient, SKIES, lighting, streetLife, TOWN.ambient]
  const version = createHash('sha256')
    .update(JSON.stringify(assets))
    .update(JSON.stringify(dynamic))
    .update(JSON.stringify(arenaConfigs))
    .update(JSON.stringify(equipment))
    .update(JSON.stringify(environment))
    .update(JSON.stringify(atmosphere))
    .update(JSON.stringify(TOWN))
    .update(collision.version)
    .digest('hex')
  await writeFile(
    'src/experiments/out-west/content/manifest.ts',
    `// Generated by tools/content/manifest.ts. Native-v2 paths preserve the prior runtime's asset contract.\nexport const DYNAMIC_ASSETS = ${JSON.stringify(dynamic)} as const\nexport const ENVIRONMENT = ${JSON.stringify(environment)} as const\nexport const CONTENT_VERSION = '${version}'\nexport const COLLISION_VERSION = '${collision.version}'\nexport const ASSETS = ${JSON.stringify(assets, null, 2)} as const\nexport const TOWN_BOUNDS = { minX: 0, minZ: 0, maxX: ${TOWN.size}, maxZ: ${TOWN.size} } as const\nexport const FRONTIER_SPAWN = ${JSON.stringify(arrival)} as const\n`,
  )
  await formatContent([
    'src/experiments/out-west/content/ambient.ts',
    'src/experiments/out-west/content/equipment.ts',
    'src/experiments/out-west/content/manifest.ts',
  ])
}
if (import.meta.main) {
  await buildManifest()
}
