/** Figure units to metres: 100 units is 1.82 m. */
export const UNIT = 0.0182
/** Shadow length per unit of height (the low sun). */
export const SHADOW = 1.05

export interface Gunman {
  shape: Pt[]
  x: number
  z: number
  facing: 1 | -1
}
export const GUNMEN: Gunman[] = [
  { shape: DUSTER, x: -2.2, z: 4.9, facing: 1 },
  { shape: SHORTCOAT, x: 2.25, z: 5, facing: -1 },
]

export function gunmanPts(g: Gunman): Pt[] {
  return g.shape.map(([u, v]) => proj(g.x + u * UNIT * g.facing, -v * UNIT, g.z))
}
/** The shadow on the street, cast straight at the viewer by a sun at the vanishing point. */
export function shadowPts(g: Gunman): Pt[] {
  return g.shape.map(([u, v]) => proj(g.x + u * UNIT * g.facing, 0, g.z + v * UNIT * SHADOW))
}
