/**
 * Bakes the Outfitter's item thumbnails into static images, so the store never dresses a
 * gunslinger at runtime just to draw a card (each worn piece was a full dress-and-bake plus a
 * pixel read: 100+ ms frames at the floor proxy's 4× throttle).
 *
 *   bun run dev --port 4385          # in another shell
 *   bun tools/item-thumbs.ts [baseUrl]
 *
 * Renders every catalog item through the game's own `ItemStudio` (the dev-only `__ow` hook,
 * `#debug`) at 2× density, writes `public/experiments/out-west/thumbs/<id>.webp`, and lists the
 * baked ids in `src/experiments/out-west/ui/thumbs.ts`. Items without a file still render at
 * runtime, one per frame. Re-run it when kit art changes.
 */
import { mkdirSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { chromium } from 'playwright'
import { CATALOG } from '../src/experiments/out-west/data/catalog.ts'
import { hasThumb } from '../src/experiments/out-west/scene/item-studio.ts'
import { fileHash, itemArtFingerprint } from './item-art.ts'

const SHADER_ERROR = /WebGL|Shader|GL_INVALID|program not valid/u
const base = process.argv.find((a) => a.startsWith('http')) ?? 'http://localhost:4385'
const root = new URL('../', import.meta.url).pathname
const outDir = `${root}public/experiments/out-west/thumbs`
mkdirSync(outDir, { recursive: true })

const fingerprint = itemArtFingerprint()
const errors: string[] = []
const browser = await chromium.launch({ channel: 'chrome', args: ['--use-angle=metal'] })
const baked: string[] = []
try {
  const page = await (
    await browser.newContext({ viewport: { width: 900, height: 600 }, deviceScaleFactor: 2 })
  ).newPage()
  page.on('pageerror', (error) => errors.push(error.message))
  page.on('console', (message) => {
    if (message.type() === 'error' && SHADER_ERROR.test(message.text())) {
      errors.push(message.text())
    }
  })
  await page.routeWebSocket(
    (url) => url.host === new URL(base).host,
    (socket) => socket.send(JSON.stringify({ type: 'connected' })),
  )
  await page.goto(`${base}/experiments/out-west/#debug&tier=high`)
  await page.waitForFunction(() => Reflect.get(globalThis, '__ow') !== undefined, null, {
    timeout: 180_000,
  })
  for (const item of CATALOG) {
    const url = await page.evaluate((id) => {
      const g = Reflect.get(globalThis, '__ow') as {
        itemThumb: (id: string) => HTMLCanvasElement | null
      }
      const c = g.itemThumb(id)
      return c ? c.toDataURL('image/webp', 0.9) : null
    }, item.id)
    if (!url) {
      if (hasThumb(item.slot)) {
        throw new Error(`Missing render for ${item.id}`)
      }
      continue
    }
    writeFileSync(`${outDir}/${item.id}.webp`, Buffer.from(url.split(',')[1] ?? '', 'base64'))
    baked.push(item.id)
  }
} finally {
  await browser.close()
}
if (errors.length > 0) {
  throw new Error(`Item rendering failed: ${errors.join('\n')}`)
}
if (itemArtFingerprint() !== fingerprint) {
  throw new Error('Character art changed during the bake. Re-run the complete thumbnail bake.')
}
writeFileSync(
  `${root}src/experiments/out-west/ui/thumbs.ts`,
  `import type { ItemId } from '../data/catalog.ts'

/**
 * Item ids with a baked Outfitter thumbnail in \`public/experiments/out-west/thumbs/<id>.webp\`
 * (generated by tools/item-thumbs.ts; re-run it when kit art changes).
 */
export const BAKED_THUMBS: ReadonlySet<ItemId> = new Set([
${baked.map((id) => `  '${id}',`).join('\n')}
])
`,
)
writeFileSync(
  `${outDir}/manifest.json`,
  `${JSON.stringify({ fingerprint, images: Object.fromEntries(baked.map((id) => [id, fileHash(`${outDir}/${id}.webp`)])) }, null, 2)}\n`,
)
console.log(`baked ${baked.length} thumbnails into ${outDir}`)
