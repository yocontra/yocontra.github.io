/** Rebuild every catalogue card from the same native GLB and PBR lighting as the game. */
import { mkdirSync, writeFileSync } from 'node:fs'
import { chromium } from 'playwright'
import { CATALOG } from '../src/experiments/out-west/data/catalog.ts'
import { fileHash, hasThumb, itemArtFingerprint } from './item-art.ts'

const base = process.argv.find((arg) => arg.startsWith('http')) ?? 'http://localhost:4389'
const hotReloadSocket = `${base.replace(/^http/u, 'ws')}/**`
const root = new URL('../', import.meta.url).pathname
const outDir = `${root}public/experiments/out-west/thumbs`
mkdirSync(outDir, { recursive: true })
const fingerprint = itemArtFingerprint()
const errors: string[] = []
const baked: string[] = []
const browser = await chromium.launch({ channel: 'chrome', headless: true })
try {
  const page = await browser.newPage({
    viewport: { width: 256, height: 256 },
    deviceScaleFactor: 1,
  })
  page.on('pageerror', (error) => errors.push(error.message))
  // Writing generated public images must not reload the preview mid-bake.
  await page.routeWebSocket(hotReloadSocket, () => undefined)
  await page.goto(`${base}/404`)
  for (const item of CATALOG.filter((candidate) => hasThumb(candidate.slot))) {
    await page.evaluate(async (id) => {
      const path = '/tools/content/item-preview.ts'
      const module = await import(/* @vite-ignore */ path)
      await module.previewItem(id)
    }, item.id)
    await page
      .locator('canvas')
      .screenshot({ path: `${outDir}/${item.id}.webp`, type: 'webp', quality: 90 })
    baked.push(item.id)
  }
} finally {
  await browser.close()
}
if (errors.length > 0) {
  throw new Error(errors.join('\n'))
}
if (itemArtFingerprint() !== fingerprint) {
  throw new Error('Art changed during build; rerun the complete bake.')
}
writeFileSync(
  `${root}src/experiments/out-west/ui/thumbs.ts`,
  `import type { ItemId } from '../data/catalog.ts'\n/** Native catalogue images generated by tools/item-thumbs.ts. */\nexport const BAKED_THUMBS: ReadonlySet<ItemId> = new Set([\n${baked.map((id) => `  '${id}',`).join('\n')}\n])\n`,
)
writeFileSync(
  `${outDir}/manifest.json`,
  `${JSON.stringify({ fingerprint, images: Object.fromEntries(baked.map((id) => [id, fileHash(`${outDir}/${id}.webp`)])) }, null, 2)}\n`,
)
console.log(`baked ${baked.length} native previews`)
